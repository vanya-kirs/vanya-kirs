# Pre-build lowercase lists for fast substring search
_POSITIVE_LOWER = [kw.lower() for kw in POSITIVE_KEYWORDS]
_STOP_LOWER = [kw.lower() for kw in STOP_KEYWORDS]
_ROLE_LOWER = [kw.lower() for kw in ROLE_KEYWORDS]


def keyword_prefilter(text: str) -> tuple[bool, str]:
    """Return (should_score, reason).

    should_score=False  → skip Claude
    should_score=True   → proceed to Claude

    Priority: STOP wins over POSITIVE.
    No match → pass through (Claude makes final call).
    """
    lower = text.lower()

    for kw in _STOP_LOWER:
        if kw in lower:
            return False, f"stop_keyword:{kw}"

    for kw in _POSITIVE_LOWER:
        if kw in lower:
            return True, f"positive_keyword:{kw}"

    return True, "no_keyword_match"


def has_role_signal(text: str) -> bool:
    """True if text contains a subject-role keyword (владелец, CEO, etc.)."""
    lower = text.lower()
    return any(kw in lower for kw in _ROLE_LOWER)
